"""
Pydantic data validation schemas for the Inferxe Inference API.
"""

from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field, field_validator


class InferenceRequest(BaseModel):
    """Customer inference payload."""
    model: Optional[str] = Field(
        default="nvidia/nemotron-3.5-bolt-e4b",
        description="Target model identifier"
    )
    prompt: str = Field(
        ...,
        description="Prompt or instruction for the language model",
        examples=["Explain GPU inference in simple words."]
    )
    max_tokens: Optional[int] = Field(
        default=300,
        ge=1,
        le=4096,
        description="Maximum tokens to generate (1 to 4096)"
    )
    temperature: Optional[float] = Field(
        default=0.2,
        ge=0.0,
        le=2.0,
        description="Sampling temperature between 0.0 (deterministic) and 2.0 (creative)"
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Prompt cannot be empty or solely whitespace.")
        return v.strip()


class UsageInfo(BaseModel):
    """Token consumption telemetry."""
    prompt_tokens: int = Field(..., ge=0, description="Tokens consumed by input prompt")
    completion_tokens: int = Field(..., ge=0, description="Tokens generated by model")
    total_tokens: int = Field(..., ge=0, description="Sum of prompt and completion tokens")


class InferenceResponse(BaseModel):
    """Successful inference result."""
    success: bool = True
    provider: str = Field(default="nvidia", description="Serving infrastructure provider")
    model: str = Field(..., description="Model executed")
    response: str = Field(..., description="Text content generated by model")
    usage: UsageInfo = Field(..., description="Detailed token metrics")


class ErrorResponse(BaseModel):
    """Standardized API error message."""
    success: bool = False
    error: str = Field(..., description="Error message description")
    code: str = Field(..., description="Error code identifier")


class HealthResponse(BaseModel):
    """System health and dependency status."""
    status: str
    service: str = "inferxe-inference-api"
    database: str
    nvidia_provider: str
    version: str = "1.0.0"


class APIKeyCreateRequest(BaseModel):
    """Request payload to generate a new customer API key."""
    name: Optional[str] = Field(default="Default Key", max_length=100)
    environment: Optional[str] = Field(default="live", pattern="^(live|test)$")


class APIKeyCreateResponse(BaseModel):
    """Response containing newly generated customer API key (shown only once)."""
    id: str
    name: str
    key_prefix: str
    api_key: str = Field(..., description="Customer API key - please store securely, shown once")
    environment: str
    created_at: str


class APIKeyItem(BaseModel):
    """Public customer API key metadata without secrets or hashes."""
    id: str
    user_id: Optional[str] = None
    name: str
    key_prefix: str
    environment: str
    is_active: bool
    created_at: str
    last_used_at: Optional[str] = None
    revoked_at: Optional[str] = None


class APIKeyListResponse(BaseModel):
    """List of customer API keys."""
    success: bool = True
    keys: List[APIKeyItem]


class SSHKeyCreateRequest(BaseModel):
    """Request payload to register a new customer SSH public key."""
    name: Optional[str] = Field(default="Default SSH Key", max_length=100, description="User-friendly label or machine name")
    public_key: str = Field(..., description="OpenSSH public key string")

    @field_validator("public_key")
    @classmethod
    def validate_public_key_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Public key cannot be empty or solely whitespace.")
        return v.strip()


class SSHKeyResponse(BaseModel):
    """Metadata response for a registered SSH public key."""
    id: str
    name: str
    public_key: str
    fingerprint: str
    key_type: str
    created_at: str


class SSHKeyItem(BaseModel):
    """SSH key metadata in list view."""
    id: str
    name: str
    public_key: str
    fingerprint: str
    key_type: str
    created_at: str


class SSHKeyListResponse(BaseModel):
    """List response of customer's registered SSH public keys."""
    success: bool = True
    keys: List[SSHKeyItem]


class SSHKeyDeleteResponse(BaseModel):
    """Response payload for SSH key deletion."""
    success: bool = True
    message: str
    id: str


class APIKeyRevokeResponse(BaseModel):
    """Response for key revocation."""
    success: bool = True
    message: str
    id: str

class NotebookCreateRequest(BaseModel):
    """Payload to create and provision a new notebook instance."""
    name: Optional[str] = Field(default="Untitled Notebook", max_length=255, description="Notebook session name")
    gpu_profile: Optional[str] = Field(default="NVIDIA L4", max_length=128, description="Target GPU model / tier")
    selected_ssh_key_id: Optional[str] = Field(default=None, description="UUID of registered customer SSH key")

    @field_validator("name")
    @classmethod
    def validate_name_not_empty(cls, v: Optional[str]) -> str:
        if v is not None and not v.strip():
            raise ValueError("Notebook name cannot be solely whitespace.")
        return (v or "Untitled Notebook").strip()


class NotebookResponse(BaseModel):
    """Detailed notebook instance metadata."""
    id: str
    user_id: str
    name: str
    gpu_profile: str
    status: str
    runtime_type: str
    runtime_reference: Optional[str] = None
    selected_ssh_key_id: Optional[str] = None
    ssh_command: Optional[str] = None
    jupyter_url: Optional[str] = None
    access_token: Optional[str] = Field(
        default=None,
        description="One-time raw session token returned only upon creation"
    )
    is_simulated: bool = Field(default=True, description="True when running in simulated runtime mode")
    simulation_notice: str = Field(
        default="Simulated runtime environment: no physical GPU or Jupyter container is running."
    )
    created_at: str
    updated_at: str
    last_active_at: Optional[str] = None


class NotebookListResponse(BaseModel):
    """List response of customer's notebook instances."""
    success: bool = True
    notebooks: List[NotebookResponse]


class NotebookActionResponse(BaseModel):
    """Action response for notebook lifecycle events (start, stop, terminate)."""
    success: bool = True
    message: str
    notebook: NotebookResponse

