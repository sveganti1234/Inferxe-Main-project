"""
schemas.py
==========
Pydantic data validation schemas for the Inferxe Inference API.
"""

from typing import Optional, Dict, Any, List
from pydantic import BaseModel, Field, field_validator


class InferenceRequest(BaseModel):
    """Customer inference payload."""
    model: Optional[str] = Field(
        default="nvidia/nemotron-3.5-bolt-e4b",
        description="Target model identifier"
    )
    prompt: str = Field(
        ...,
        description="Prompt or instruction for the language model",
        examples=["Explain GPU inference in simple words."]
    )
    max_tokens: Optional[int] = Field(
        default=300,
        ge=1,
        le=4096,
        description="Maximum tokens to generate (1 to 4096)"
    )
    temperature: Optional[float] = Field(
        default=0.2,
        ge=0.0,
        le=2.0,
        description="Sampling temperature between 0.0 (deterministic) and 2.0 (creative)"
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Prompt cannot be empty or solely whitespace.")
        return v.strip()


class UsageInfo(BaseModel):
    """Token consumption telemetry."""
    prompt_tokens: int = Field(..., ge=0, description="Tokens consumed by input prompt")
    completion_tokens: int = Field(..., ge=0, description="Tokens generated by model")
    total_tokens: int = Field(..., ge=0, description="Sum of prompt and completion tokens")


class InferenceResponse(BaseModel):
    """Successful inference result."""
    success: bool = True
    provider: str = Field(default="nvidia", description="Serving infrastructure provider")
    model: str = Field(..., description="Model executed")
    response: str = Field(..., description="Text content generated by model")
    usage: UsageInfo = Field(..., description="Detailed token metrics")


class ErrorResponse(BaseModel):
    """Standardized API error message."""
    success: bool = False
    error: str = Field(..., description="Error message description")
    code: str = Field(..., description="Error code identifier")


class HealthResponse(BaseModel):
    """System health and dependency status."""
    status: str
    service: str = "inferxe-inference-api"
    database: str
    nvidia_provider: str
    version: str = "1.0.0"


class APIKeyCreateRequest(BaseModel):
    """Request payload to generate a new customer API key."""
    name: Optional[str] = Field(default="Default Key", max_length=100)
    environment: Optional[str] = Field(default="live", pattern="^(live|test)$")


class APIKeyCreateResponse(BaseModel):
    """Response containing newly generated customer API key (shown only once)."""
    id: str
    name: str
    key_prefix: str
    api_key: str = Field(..., description="Customer API key - please store securely, shown once")
    environment: str
    created_at: str


class APIKeyItem(BaseModel):
    """Public customer API key metadata without secrets or hashes."""
    id: str
    user_id: Optional[str] = None
    name: str
    key_prefix: str
    environment: str
    is_active: bool
    created_at: str
    last_used_at: Optional[str] = None
    revoked_at: Optional[str] = None


class APIKeyListResponse(BaseModel):
    """List of customer API keys."""
    success: bool = True
    keys: List[APIKeyItem]


class APIKeyRevokeResponse(BaseModel):
    """Response for key revocation."""
    success: bool = True
    message: str
    id: str

